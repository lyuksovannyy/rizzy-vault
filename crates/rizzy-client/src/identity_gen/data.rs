//! The bundled identity data: its text format and a size-limited parser that never panics
//! ([ADR 0079] §5).
//!
//! The file is the compiled output of `cargo xtask identity-data` (ADR 0079 §6), never edited by
//! hand. Each country is one block: `@` directives (code, English name, titles, address
//! pattern, house-number range, postcode and phone patterns), then `[section]` lists (first
//! names by sex, last names, streets, cities, subdivisions and, for some countries,
//! per-subdivision postcode patterns). The exact grammar is pinned below and by the tests:
//!
//! - UTF-8, LF line ends, no blank lines, at most [`MAX_DATA_LEN`] bytes and [`MAX_LINE_LEN`]
//!   bytes per line; line 1 is [`HEADER`]; countries in ascending code order.
//! - Directives, in this order: `@country CC`, `@name`, `@title.male`, `@title.female`,
//!   `@address` (one `{street}` and one `{number}`), `@number LO HI`, one or more
//!   `@postcode`, zero or more `@phone`.
//! - Sections, in this order: `[first.female]`, `[first.male]`, then `[last]` or
//!   `[last.female]` and `[last.male]`, `[street]`, `[city]`, `[subdivision]`, and an optional
//!   `[postcode]`. Names are `display|ascii`; cities are `city` or `city|SUBDIVISION`;
//!   subdivisions are `ISO-3166-2|written form`; `[postcode]` lines are `SUBDIVISION|pattern`.
//! - Every list is in strictly ascending byte order, so it has no duplicates; the name, street
//!   and city lists hold at least [`MIN_LIST`] entries and at most their caps.
//! - Display forms are 1–40 bytes of Latin letters (ASCII and U+00C0–U+024F, without × and ÷,
//!   all precomposed, so an accepted entry is NFC), spaces, hyphens and apostrophes; ascii forms
//!   are 1–32 bytes of `[a-z-]` with no leading, trailing or doubled hyphen.
//!
//! [ADR 0079]: https://github.com/lyuksovannyy/rizzy-vault/blob/main/docs/adr/0079-identity-generator.md

use core::fmt;

/// The first line of every identity data file.
pub const HEADER: &str = "# identity-data v1. Generated by `cargo xtask identity-data`; do not edit. Provenance: data/identity/SOURCES.md";
/// The size budget of the data file, 384 KiB (ADR 0079 §5).
pub const MAX_DATA_LEN: usize = 384 * 1024;
/// The longest line accepted.
pub const MAX_LINE_LEN: usize = 200;
/// The fewest entries a name, street or city list may have (ADR 0079 §5).
pub const MIN_LIST: usize = 50;
/// The most countries a file may hold.
pub const MAX_COUNTRIES: usize = 32;
/// The cap on first names per sex (ADR 0079 §5).
pub const MAX_FIRST_NAMES: usize = 400;
/// The cap on last names, per sex where split (ADR 0079 §5).
pub const MAX_LAST_NAMES: usize = 800;
/// The cap on streets (ADR 0079 §5).
pub const MAX_STREETS: usize = 400;
/// The cap on cities (ADR 0079 §5).
pub const MAX_CITIES: usize = 400;
/// The most subdivisions a country may have.
pub const MAX_SUBDIVISIONS: usize = 128;
/// The most `@postcode` patterns a country may have.
pub const MAX_POSTCODE_PATTERNS: usize = 512;
/// The most `@phone` patterns a country may have.
pub const MAX_PHONE_PATTERNS: usize = 16;
/// The most `[postcode]` lines a country may have.
pub const MAX_SUBDIVISION_POSTCODES: usize = 1024;

/// The longest display form (ADR 0079 §5).
const MAX_DISPLAY_LEN: usize = 40;
/// The longest ascii form (ADR 0079 §5).
const MAX_ASCII_LEN: usize = 32;
/// The longest title.
const MAX_TITLE_LEN: usize = 16;
/// The longest postcode pattern.
const MAX_POSTCODE_LEN: usize = 16;
/// The longest phone pattern.
const MAX_PHONE_LEN: usize = 24;

/// Why identity data was refused. Carries no data from the file beyond a line number.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum IdentityDataError {
    /// Longer than [`MAX_DATA_LEN`].
    TooLarge,
    /// Not UTF-8.
    NotUtf8,
    /// Line 1 is not [`HEADER`], or the file does not end with a line feed.
    Header,
    /// The 1-based line breaks a rule of the format.
    Line(usize),
    /// The country block ending at this 1-based line lacks a required directive or section,
    /// or a list is shorter than [`MIN_LIST`].
    Incomplete(usize),
    /// The file holds no country.
    Empty,
}

impl fmt::Display for IdentityDataError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TooLarge => f.write_str("identity data is larger than its budget"),
            Self::NotUtf8 => f.write_str("identity data is not UTF-8"),
            Self::Header => f.write_str("identity data has no valid header or final line feed"),
            Self::Line(n) => write!(f, "identity data line {n} is malformed"),
            Self::Incomplete(n) => {
                write!(f, "identity data country ending at line {n} is incomplete")
            }
            Self::Empty => f.write_str("identity data holds no country"),
        }
    }
}

impl core::error::Error for IdentityDataError {}

/// A name: its display form and the ascii form an email local part uses.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Name<'a> {
    /// As shown, for example `Jürgen`.
    pub display: &'a str,
    /// `[a-z-]`, for example `juergen`.
    pub ascii: &'a str,
}

/// Last names: one list, or one per sex where surnames change with it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum Surnames<'a> {
    /// One list for both sexes (`[last]`).
    Shared(Vec<Name<'a>>),
    /// `[last.female]` and `[last.male]`.
    Split {
        /// Female surnames.
        female: Vec<Name<'a>>,
        /// Male surnames.
        male: Vec<Name<'a>>,
    },
}

/// A city, with the index of its subdivision where the data pairs them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct City<'a> {
    /// The city's name.
    pub(crate) name: &'a str,
    /// The index of its paired subdivision, if the data pairs them.
    pub(crate) subdivision: Option<usize>,
}

/// A subdivision: its ISO 3166-2 code, its written form, and its own postcode patterns.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct Subdivision<'a> {
    /// The ISO 3166-2 code.
    pub(crate) code: &'a str,
    /// The form addresses use (written into `identity.state`).
    pub(crate) written: &'a str,
    /// Its own postcode patterns; empty means the country's.
    pub(crate) postcodes: Vec<&'a str>,
}

/// One country's data.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Country<'a> {
    /// `@country`.
    pub(crate) code: &'a str,
    /// `@name`.
    pub(crate) name: &'a str,
    /// `@title.male`.
    pub(crate) title_male: &'a str,
    /// `@title.female`.
    pub(crate) title_female: &'a str,
    /// `@address`, with `{street}` and `{number}`.
    pub(crate) address: &'a str,
    /// `@number`: the house-number range, inclusive.
    pub(crate) number: (u16, u16),
    /// `@postcode` patterns.
    pub(crate) postcodes: Vec<&'a str>,
    /// `@phone` patterns (fictional ranges only).
    pub(crate) phones: Vec<&'a str>,
    /// `[first.female]`.
    pub(crate) first_female: Vec<Name<'a>>,
    /// `[first.male]`.
    pub(crate) first_male: Vec<Name<'a>>,
    /// `[last]`, or `[last.female]` and `[last.male]`.
    pub(crate) last: Surnames<'a>,
    /// `[street]`.
    pub(crate) streets: Vec<&'a str>,
    /// `[city]`.
    pub(crate) cities: Vec<City<'a>>,
    /// `[subdivision]`, with `[postcode]` folded in.
    pub(crate) subdivisions: Vec<Subdivision<'a>>,
}

impl<'a> Country<'a> {
    /// The ISO 3166-1 alpha-2 code, upper case.
    #[must_use]
    pub const fn code(&self) -> &'a str {
        self.code
    }

    /// The CLDR English name.
    #[must_use]
    pub const fn name(&self) -> &'a str {
        self.name
    }

    /// The written forms of the country's subdivisions, in code order.
    pub fn subdivision_names(&self) -> impl Iterator<Item = &'a str> + '_ {
        self.subdivisions.iter().map(|s| s.written)
    }

    /// The postcode patterns that apply to a subdivision: its own if the data has them, else
    /// the country's (ADR 0079 §4 step 7).
    pub(crate) fn postcode_patterns(&self, subdivision: usize) -> &[&'a str] {
        match self.subdivisions.get(subdivision) {
            Some(s) if !s.postcodes.is_empty() => &s.postcodes,
            _ => &self.postcodes,
        }
    }

    /// The country's postcode patterns and every subdivision's (for tests and checks).
    pub fn all_postcode_patterns(&self) -> impl Iterator<Item = &'a str> + '_ {
        self.postcodes.iter().copied().chain(
            self.subdivisions
                .iter()
                .flat_map(|s| s.postcodes.iter().copied()),
        )
    }

    /// Whether the country has fictional phone ranges (ADR 0079 §7).
    #[must_use]
    pub fn has_phone(&self) -> bool {
        !self.phones.is_empty()
    }
}

/// Parsed identity data, borrowing from the file text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IdentityData<'a> {
    /// The countries, in ascending code order.
    countries: Vec<Country<'a>>,
}

impl<'a> IdentityData<'a> {
    /// The countries, in code order.
    #[must_use]
    pub fn countries(&self) -> &[Country<'a>] {
        &self.countries
    }

    /// The country with this upper-case code.
    #[must_use]
    pub fn country(&self, code: &str) -> Option<&Country<'a>> {
        self.countries
            .binary_search_by(|c| c.code.cmp(code))
            .ok()
            .and_then(|i| self.countries.get(i))
    }
}

// --- the parser -------------------------------------------------------------------------------

/// The parser's position inside a country block. Directives first, then sections, in order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Stage {
    /// After `@country`.
    Country,
    /// After `@name`.
    Name,
    /// After `@title.male`.
    TitleMale,
    /// After `@title.female`.
    TitleFemale,
    /// After `@address`.
    Address,
    /// After `@number`.
    Number,
    /// After one or more `@postcode`.
    Postcode,
    /// After one or more `@phone`.
    Phone,
    /// In `[first.female]`.
    FirstFemale,
    /// In `[first.male]`.
    FirstMale,
    /// In `[last]`.
    Last,
    /// In `[last.female]`.
    LastFemale,
    /// In `[last.male]`.
    LastMale,
    /// In `[street]`.
    Street,
    /// In `[city]`.
    City,
    /// In `[subdivision]`.
    Subdivision,
    /// In `[postcode]`.
    SubdivisionPostcode,
}

/// A country block being parsed; its fields mirror [`Country`]'s.
#[derive(Debug)]
struct Builder<'a> {
    /// Where the parser is in the block.
    stage: Stage,
    /// `@country`.
    code: &'a str,
    /// `@name`.
    name: &'a str,
    /// `@title.male`.
    title_male: &'a str,
    /// `@title.female`.
    title_female: &'a str,
    /// `@address`.
    address: &'a str,
    /// `@number`.
    number: (u16, u16),
    /// `@postcode` patterns.
    postcodes: Vec<&'a str>,
    /// `@phone` patterns.
    phones: Vec<&'a str>,
    /// `[first.female]`.
    first_female: Vec<Name<'a>>,
    /// `[first.male]`.
    first_male: Vec<Name<'a>>,
    /// `[last]` or `[last.female]`.
    last: Vec<Name<'a>>,
    /// `[last.male]`; empty when surnames are shared.
    last_male: Vec<Name<'a>>,
    /// `[street]`.
    streets: Vec<&'a str>,
    /// `[city]`, with the subdivision code to resolve at the end of the block.
    cities: Vec<(&'a str, Option<&'a str>)>,
    /// `[subdivision]`, with their `[postcode]` lines.
    subdivisions: Vec<Subdivision<'a>>,
    /// The previous entry's sort key in the current section.
    last_key: (&'a str, &'a str),
    /// How many `[postcode]` lines were read.
    subdivision_postcodes: usize,
}

impl<'a> Builder<'a> {
    /// An empty block for `code`.
    const fn new(code: &'a str) -> Self {
        Self {
            stage: Stage::Country,
            code,
            name: "",
            title_male: "",
            title_female: "",
            address: "",
            number: (0, 0),
            postcodes: Vec::new(),
            phones: Vec::new(),
            first_female: Vec::new(),
            first_male: Vec::new(),
            last: Vec::new(),
            last_male: Vec::new(),
            streets: Vec::new(),
            cities: Vec::new(),
            subdivisions: Vec::new(),
            last_key: ("", ""),
            subdivision_postcodes: 0,
        }
    }

    /// Reads an `@` directive in its place.
    fn directive(&mut self, name: &str, value: &'a str) -> Option<()> {
        match (name, self.stage) {
            ("name", Stage::Country) if display(value) => {
                self.name = value;
                self.stage = Stage::Name;
            }
            ("title.male", Stage::Name) if title(value) => {
                self.title_male = value;
                self.stage = Stage::TitleMale;
            }
            ("title.female", Stage::TitleMale) if title(value) => {
                self.title_female = value;
                self.stage = Stage::TitleFemale;
            }
            ("address", Stage::TitleFemale) if address(value) => {
                self.address = value;
                self.stage = Stage::Address;
            }
            ("number", Stage::Address) => {
                self.number = number_range(value)?;
                self.stage = Stage::Number;
            }
            ("postcode", Stage::Number | Stage::Postcode)
                if postcode(value) && self.postcodes.len() < MAX_POSTCODE_PATTERNS =>
            {
                self.postcodes.push(value);
                self.stage = Stage::Postcode;
            }
            ("phone", Stage::Postcode | Stage::Phone)
                if phone(value) && self.phones.len() < MAX_PHONE_PATTERNS =>
            {
                self.phones.push(value);
                self.stage = Stage::Phone;
            }
            _ => return None,
        }
        Some(())
    }

    /// Moves to a new section, checking that the one it leaves is long enough.
    fn section(&mut self, name: &str) -> Option<()> {
        let next = match (name, self.stage) {
            ("first.female", Stage::Postcode | Stage::Phone) => Stage::FirstFemale,
            ("first.male", Stage::FirstFemale) => Stage::FirstMale,
            ("last", Stage::FirstMale) => Stage::Last,
            ("last.female", Stage::FirstMale) => Stage::LastFemale,
            ("last.male", Stage::LastFemale) => Stage::LastMale,
            ("street", Stage::Last | Stage::LastMale) => Stage::Street,
            ("city", Stage::Street) => Stage::City,
            ("subdivision", Stage::City) => Stage::Subdivision,
            ("postcode", Stage::Subdivision) => Stage::SubdivisionPostcode,
            _ => return None,
        };
        self.leave_section()?;
        self.stage = next;
        self.last_key = ("", "");
        Some(())
    }

    /// The minimum-length rule for the section being left.
    fn leave_section(&self) -> Option<()> {
        let len = match self.stage {
            Stage::FirstFemale => self.first_female.len(),
            Stage::FirstMale => self.first_male.len(),
            Stage::Last | Stage::LastFemale => self.last.len(),
            Stage::LastMale => self.last_male.len(),
            Stage::Street => self.streets.len(),
            Stage::City => self.cities.len(),
            Stage::Subdivision => return (!self.subdivisions.is_empty()).then_some(()),
            _ => return Some(()),
        };
        (len >= MIN_LIST).then_some(())
    }

    /// Reads one entry line of the current section.
    fn entry(&mut self, line: &'a str) -> Option<()> {
        // Strictly ascending keys (the part before `|`; for `[postcode]` the whole pair), so
        // the list is sorted and has no duplicates.
        let key = line.split_once('|').unwrap_or((line, ""));
        let ascending = match self.stage {
            Stage::SubdivisionPostcode => key > self.last_key,
            _ => key.0 > self.last_key.0,
        };
        if !ascending {
            return None;
        }
        match self.stage {
            Stage::FirstFemale => push_name(&mut self.first_female, line, MAX_FIRST_NAMES)?,
            Stage::FirstMale => push_name(&mut self.first_male, line, MAX_FIRST_NAMES)?,
            Stage::Last | Stage::LastFemale => push_name(&mut self.last, line, MAX_LAST_NAMES)?,
            Stage::LastMale => push_name(&mut self.last_male, line, MAX_LAST_NAMES)?,
            Stage::Street => {
                if !display(line) || self.streets.len() >= MAX_STREETS {
                    return None;
                }
                self.streets.push(line);
            }
            Stage::City => {
                let (city, sub) = match line.split_once('|') {
                    Some((c, s)) => (c, Some(s)),
                    None => (line, None),
                };
                if !display(city) || self.cities.len() >= MAX_CITIES {
                    return None;
                }
                if let Some(s) = sub {
                    subdivision_code(self.code, s)?;
                }
                self.cities.push((city, sub));
            }
            Stage::Subdivision => {
                let (code, written) = line.split_once('|')?;
                subdivision_code(self.code, code)?;
                if !display(written) || self.subdivisions.len() >= MAX_SUBDIVISIONS {
                    return None;
                }
                self.subdivisions.push(Subdivision {
                    code,
                    written,
                    postcodes: Vec::new(),
                });
            }
            Stage::SubdivisionPostcode => {
                let (code, pattern) = line.split_once('|')?;
                if !postcode(pattern) || self.subdivision_postcodes >= MAX_SUBDIVISION_POSTCODES {
                    return None;
                }
                let i = self
                    .subdivisions
                    .binary_search_by(|s| s.code.cmp(code))
                    .ok()?;
                self.subdivisions.get_mut(i)?.postcodes.push(pattern);
                self.subdivision_postcodes += 1;
            }
            _ => return None,
        }
        self.last_key = key;
        Some(())
    }

    /// Closes the block: every required part present, city subdivisions resolved.
    fn finish(self) -> Option<Country<'a>> {
        if self.stage < Stage::Subdivision {
            return None;
        }
        self.leave_section()?;
        let last = if self.last_male.is_empty() {
            Surnames::Shared(self.last)
        } else {
            Surnames::Split {
                female: self.last,
                male: self.last_male,
            }
        };
        let mut cities = Vec::with_capacity(self.cities.len());
        for (name, sub) in self.cities {
            let subdivision = match sub {
                Some(code) => Some(
                    self.subdivisions
                        .binary_search_by(|s| s.code.cmp(code))
                        .ok()?,
                ),
                None => None,
            };
            cities.push(City { name, subdivision });
        }
        Some(Country {
            code: self.code,
            name: self.name,
            title_male: self.title_male,
            title_female: self.title_female,
            address: self.address,
            number: self.number,
            postcodes: self.postcodes,
            phones: self.phones,
            first_female: self.first_female,
            first_male: self.first_male,
            last,
            streets: self.streets,
            cities,
            subdivisions: self.subdivisions,
        })
    }
}

/// Parses identity data. Never panics; refuses anything outside the format.
///
/// # Errors
/// [`IdentityDataError`] naming the first rule broken.
pub fn parse(bytes: &[u8]) -> Result<IdentityData<'_>, IdentityDataError> {
    if bytes.len() > MAX_DATA_LEN {
        return Err(IdentityDataError::TooLarge);
    }
    let text = core::str::from_utf8(bytes).map_err(|_| IdentityDataError::NotUtf8)?;
    let body = text.strip_suffix('\n').ok_or(IdentityDataError::Header)?;
    let mut lines = (1usize..).zip(body.split('\n'));
    if lines.next().map(|(_, l)| l) != Some(HEADER) {
        return Err(IdentityDataError::Header);
    }
    let mut countries: Vec<Country<'_>> = Vec::new();
    let mut current: Option<Builder<'_>> = None;
    let mut last_number = 1;
    for (n, line) in lines {
        last_number = n;
        if line.len() > MAX_LINE_LEN {
            return Err(IdentityDataError::Line(n));
        }
        if let Some(rest) = line.strip_prefix('@') {
            let (name, value) = rest.split_once(' ').ok_or(IdentityDataError::Line(n))?;
            if name == "country" {
                if let Some(done) = current.take() {
                    countries.push(done.finish().ok_or(IdentityDataError::Incomplete(n - 1))?);
                }
                let ascending = countries.last().is_none_or(|c| c.code < value);
                if !country_code(value) || !ascending || countries.len() >= MAX_COUNTRIES {
                    return Err(IdentityDataError::Line(n));
                }
                current = Some(Builder::new(value));
            } else {
                current
                    .as_mut()
                    .and_then(|b| b.directive(name, value))
                    .ok_or(IdentityDataError::Line(n))?;
            }
        } else if let Some(name) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            current
                .as_mut()
                .and_then(|b| b.section(name))
                .ok_or(IdentityDataError::Line(n))?;
        } else {
            current
                .as_mut()
                .and_then(|b| b.entry(line))
                .ok_or(IdentityDataError::Line(n))?;
        }
    }
    if let Some(done) = current.take() {
        countries.push(
            done.finish()
                .ok_or(IdentityDataError::Incomplete(last_number))?,
        );
    }
    if countries.is_empty() {
        return Err(IdentityDataError::Empty);
    }
    Ok(IdentityData { countries })
}

/// Reads a `display|ascii` name into `list`.
fn push_name<'a>(list: &mut Vec<Name<'a>>, line: &'a str, cap: usize) -> Option<()> {
    let (display_form, ascii_form) = line.split_once('|')?;
    if list.len() >= cap || !display(display_form) || !ascii(ascii_form) {
        return None;
    }
    list.push(Name {
        display: display_form,
        ascii: ascii_form,
    });
    Some(())
}

/// A Latin letter of the v1 data: ASCII, or U+00C0–U+024F without × (U+00D7) and ÷ (U+00F7).
fn is_letter(c: char) -> bool {
    c.is_ascii_alphabetic()
        || (('\u{c0}'..='\u{24f}').contains(&c) && c != '\u{d7}' && c != '\u{f7}')
}

/// A display form: 1–40 bytes of letters, spaces, hyphens and apostrophes, with at least one
/// letter, no leading or trailing space and no double space.
pub(crate) fn display(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_DISPLAY_LEN
        && !s.starts_with(' ')
        && !s.ends_with(' ')
        && !s.contains("  ")
        && s.chars().any(is_letter)
        && s.chars()
            .all(|c| is_letter(c) || matches!(c, ' ' | '-' | '\''))
}

/// An ascii form: 1–32 bytes of `[a-z-]`, no leading, trailing or doubled hyphen.
pub(crate) fn ascii(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_ASCII_LEN
        && !s.starts_with('-')
        && !s.ends_with('-')
        && !s.contains("--")
        && s.bytes().all(|b| b.is_ascii_lowercase() || b == b'-')
}

/// A title: 1–16 bytes of letters, dots and spaces.
fn title(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_TITLE_LEN
        && !s.starts_with(' ')
        && !s.ends_with(' ')
        && s.chars().all(|c| is_letter(c) || matches!(c, '.' | ' '))
}

/// An address pattern: one `{street}`, one `{number}`, letters, spaces and commas.
fn address(s: &str) -> bool {
    s.len() <= MAX_DISPLAY_LEN
        && s.matches("{street}").count() == 1
        && s.matches("{number}").count() == 1
        && s.replace("{street}", "")
            .replace("{number}", "")
            .chars()
            .all(|c| is_letter(c) || matches!(c, ' ' | ','))
}

/// `LO HI`, decimal, `1 <= LO <= HI <= 9999`.
fn number_range(s: &str) -> Option<(u16, u16)> {
    let (lo, hi) = s.split_once(' ')?;
    let parse = |t: &str| -> Option<u16> {
        if t.is_empty() || t.len() > 4 || !t.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        t.parse().ok()
    };
    let (lo, hi) = (parse(lo)?, parse(hi)?);
    (1 <= lo && lo <= hi).then_some((lo, hi))
}

/// A postcode pattern: 1–16 bytes of `#`, `?`, upper-case letters, digits, spaces, hyphens.
pub(crate) fn postcode(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_POSTCODE_LEN
        && s.bytes()
            .all(|b| matches!(b, b'#' | b'?' | b'A'..=b'Z' | b'0'..=b'9' | b' ' | b'-'))
}

/// A phone pattern: 1–24 bytes of `#`, digits, spaces, `+`, `-`, `(`, `)`, with a `#`.
fn phone(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_PHONE_LEN
        && s.contains('#')
        && s.bytes()
            .all(|b| matches!(b, b'#' | b'0'..=b'9' | b' ' | b'+' | b'-' | b'(' | b')'))
}

/// Two upper-case ASCII letters.
fn country_code(s: &str) -> bool {
    s.len() == 2 && s.bytes().all(|b| b.is_ascii_uppercase())
}

/// `CC-` and 1–3 upper-case letters or digits, `CC` being the block's country.
fn subdivision_code(country: &str, code: &str) -> Option<()> {
    let suffix = code.strip_prefix(country)?.strip_prefix('-')?;
    (!suffix.is_empty()
        && suffix.len() <= 3
        && suffix
            .bytes()
            .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit()))
    .then_some(())
}
