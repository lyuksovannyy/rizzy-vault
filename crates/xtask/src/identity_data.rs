/// A fixed-seed `SplitMix64` (Steele, Lea and Flood 2014; Vigna's reference constants), used only
/// for sampling and pattern expansion, never for anything secret.
#[derive(Debug)]
pub(super) struct SplitMix64(u64);

impl SplitMix64 {
    /// The generator for one list: [`SEED`] XOR the FNV-1a hash of its label (`DE/first.female`),
    /// so each list's draw is independent of the others and of their order.
    pub(super) fn for_label(label: &str) -> Self {
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for b in label.bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
        Self(SEED ^ h)
    }

    /// The next output.
    pub(super) fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    /// A uniform index in `0..n` by rejection (no modulo bias); `0` for `n == 0`.
    pub(super) fn below(&mut self, n: usize) -> usize {
        let Ok(n64) = u64::try_from(n) else {
            return 0;
        };
        if n64 == 0 {
            return 0;
        }
        let threshold = n64.wrapping_neg() % n64;
        loop {
            let r = self.next_u64();
            if r >= threshold {
                return usize::try_from(r % n64).unwrap_or(0);
            }
        }
    }
}

/// Keeps `cap` items of `items` by a partial Fisher–Yates shuffle with [`SplitMix64::for_label`];
/// a list within its cap is returned whole. Callers sort the result.
pub(super) fn sample<T>(mut items: Vec<T>, cap: usize, label: &str) -> Vec<T> {
    if items.len() <= cap {
        return items;
    }
    let mut rng = SplitMix64::for_label(label);
    for i in 0..cap {
        let j = i + rng.below(items.len() - i);
        items.swap(i, j);
    }
    items.truncate(cap);
    items
}

/// Trims surrounding ASCII whitespace and maps U+2019 to an apostrophe: the only repairs the
/// content rules allow.
pub(super) fn normalize(s: &str) -> String {
    s.trim_matches(|c: char| c.is_ascii_whitespace())
        .replace('\u{2019}', "'")
}

/// Whether `c` is a "letter" of the v1 content rules: ASCII letters and U+00C0–U+024F apart from
/// U+00D7 and U+00F7 (all precomposed, so this also checks NFC).
pub(super) fn is_letter(c: char) -> bool {
    c.is_ascii_alphabetic()
        || (('\u{c0}'..='\u{24f}').contains(&c) && c != '\u{d7}' && c != '\u{f7}')
}

/// The display rule: 1–40 bytes of letters, spaces, hyphens and apostrophes, starting and ending
/// with a letter, with no double space.
pub(super) fn display_ok(s: &str) -> bool {
    let first_last =
        s.chars().next().is_some_and(is_letter) && s.chars().last().is_some_and(is_letter);
    (1..=40).contains(&s.len())
        && first_last
        && !s.contains("  ")
        && s.chars()
            .all(|c| is_letter(c) || c == ' ' || c == '-' || c == '\'')
}

/// The postcode pattern rule: 1–16 bytes of `#`, `?`, `A`–`Z`, `0`–`9`, space and `-`.
pub(super) fn postcode_ok(s: &str) -> bool {
    (1..=16).contains(&s.len())
        && s.bytes().all(|b| {
            matches!(b, b'#' | b'?' | b' ' | b'-') || b.is_ascii_uppercase() || b.is_ascii_digit()
        })
}

/// The phone pattern rule: 1–24 bytes of `#`, digits, space, `+`, `-`, `(`, `)`, with a `#`.
pub(super) fn phone_ok(s: &str) -> bool {
    (1..=24).contains(&s.len())
        && s.contains('#')
        && s.bytes()
            .all(|b| matches!(b, b'#' | b' ' | b'+' | b'-' | b'(' | b')') || b.is_ascii_digit())
}

/// The title rule: 1–16 bytes of ASCII letters, `.` and space.
pub(super) fn title_ok(s: &str) -> bool {
    (1..=16).contains(&s.len())
        && s.bytes()
            .all(|b| b.is_ascii_alphabetic() || b == b'.' || b == b' ')
}

/// Lower-case hex SHA-256.
pub(super) fn hex_sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut s, b| {
            let _ = write!(s, "{b:02x}");
            s
        })
}

/// The input block of [`SOURCES`]: `(source, path)` → SHA-256.
///
/// # Errors
///
/// When the block is missing, repeated or unterminated, or a line is not
/// `<faker|cldr> <relative path> <64 hex>`, or a pair repeats.
pub(super) fn manifest(sources: &str) -> Result<BTreeMap<(String, String), String>, String> {
    let mut lines = sources.lines();
    let mut found = None;
    while let Some(line) = lines.next() {
        if line != INPUT_BLOCK {
            continue;
        }
        if found.is_some() {
            return Err(format!("{SOURCES}: the {INPUT_BLOCK} block appears twice"));
        }
        let mut map = BTreeMap::new();
        let mut closed = false;
        for entry in lines.by_ref() {
            if entry == "```" {
                closed = true;
                break;
            }
            let parts: Vec<&str> = entry.split(' ').collect();
            let [source, path, sha] = parts.as_slice() else {
                return Err(format!("{SOURCES}: malformed input line {entry:?}"));
            };
            let sha_ok = sha.len() == 64
                && sha
                    .bytes()
                    .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
            let path_ok = !path.is_empty()
                && !path.starts_with('/')
                && !path
                    .split('/')
                    .any(|p| p.is_empty() || p == "." || p == "..");
            if ![FAKER.id, CLDR.id].contains(source) || !sha_ok || !path_ok {
                return Err(format!("{SOURCES}: malformed input line {entry:?}"));
            }
            if map
                .insert(
                    ((*source).to_owned(), (*path).to_owned()),
                    (*sha).to_owned(),
                )
                .is_some()
            {
                return Err(format!("{SOURCES}: {source} {path} is listed twice"));
            }
        }
        if !closed {
            return Err(format!("{SOURCES}: the {INPUT_BLOCK} block is not closed"));
        }
        found = Some(map);
    }
    found.ok_or_else(|| format!("{SOURCES}: no {INPUT_BLOCK} block"))
}

/// Reads upstream files, checking each against the manifest; it keeps going after a failure so
/// that one run reports every missing or changed line, and [`Inputs::finish`] fails if any was.
#[derive(Debug)]
pub(super) struct Inputs {
    /// The faker checkout.
    faker: PathBuf,
    /// The CLDR checkout.
    cldr: PathBuf,
    /// The manifest.
    listed: BTreeMap<(String, String), String>,
    /// Files read, with their actual SHA-256.
    read: BTreeMap<(String, String), String>,
}

impl Inputs {
    /// A reader over the two checkouts.
    pub(super) fn new(
        faker: &Path,
        cldr: &Path,
        listed: BTreeMap<(String, String), String>,
    ) -> Self {
        Self {
            faker: faker.to_owned(),
            cldr: cldr.to_owned(),
            listed,
            read: BTreeMap::new(),
        }
    }

    /// The root of `source`.
    fn root(&self, source: &Upstream) -> &Path {
        if source.id == FAKER.id {
            &self.faker
        } else {
            &self.cldr
        }
    }

    /// Whether `path` exists in `source`'s checkout (for faker's locale fallback).
    fn exists(&self, source: &Upstream, path: &str) -> bool {
        self.root(source).join(path).is_file()
    }

    /// Reads `path` from `source` as UTF-8 and records its hash.
    ///
    /// # Errors
    ///
    /// When the file cannot be read, is over [`MAX_INPUT`] or is not UTF-8.
    fn read(&mut self, source: &Upstream, path: &str) -> Result<String, String> {
        let full = self.root(source).join(path);
        let meta = std::fs::metadata(&full).map_err(|e| format!("{}: {e}", full.display()))?;
        if meta.len() > MAX_INPUT {
            return Err(format!("{}: over {MAX_INPUT} bytes", full.display()));
        }
        let bytes = std::fs::read(&full).map_err(|e| format!("{}: {e}", full.display()))?;
        self.read
            .insert((source.id.to_owned(), path.to_owned()), hex_sha256(&bytes));
        String::from_utf8(bytes).map_err(|_| format!("{}: not UTF-8", full.display()))
    }

    /// Compares what was read with the manifest.
    ///
    /// # Errors
    ///
    /// When a file read is unlisted or changed, or a listed file was not read; the message
    /// gives the block as it would have to be.
    pub(super) fn finish(&self) -> Result<(), String> {
        let mut problems = Vec::new();
        for (key, sha) in &self.read {
            match self.listed.get(key) {
                None => problems.push(format!("not listed: {} {}", key.0, key.1)),
                Some(want) if want != sha => problems.push(format!(
                    "SHA-256 mismatch: {} {} is {sha}, listed {want}",
                    key.0, key.1
                )),
                Some(_) => {}
            }
        }
        for key in self.listed.keys() {
            if !self.read.contains_key(key) {
                problems.push(format!("listed but not read: {} {}", key.0, key.1));
            }
        }
        if problems.is_empty() {
            return Ok(());
        }
        let mut msg = format!(
            "identity-data: the inputs do not match {SOURCES}; nothing was written:\n  {}\n\
             The block for the files this run read (review before pasting):\n{INPUT_BLOCK}\n",
            problems.join("\n  ")
        );
        for ((source, path), sha) in &self.read {
            let _ = writeln!(msg, "{source} {path} {sha}");
        }
        msg.push_str("```");
        Err(msg)
    }

    /// The verified (source, path, SHA-256) triples, for the report.
    fn verified(&self) -> impl Iterator<Item = (&str, &str, &str)> {
        self.read
            .iter()
            .map(|((s, p), h)| (s.as_str(), p.as_str(), h.as_str()))
    }
}

