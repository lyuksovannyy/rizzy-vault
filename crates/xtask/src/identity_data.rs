//! `cargo xtask identity-data --faker <checkout> --cldr <checkout> [--check]` (ADR 0079 §6): compiles
//! the identity generator's bundled data, [`OUTPUT`], from local checkouts of the pinned
//! upstream tags of faker-js ([`FAKER`]) and Unicode CLDR ([`CLDR`]). It does no network I/O, so
//! a run is reproducible; the maintainer fetches the checkouts ([`SOURCES`] says how).
//!
//! # Steps
//!
//! 1. **Verification.** Every upstream file the run reads must be listed, with its SHA-256, in
//!    the `` ```identity-data-inputs `` block of [`SOURCES`] ([`manifest`]), and every listed file must
//!    be read. A missing, unlisted or changed file fails the run before anything is written;
//!    the error lists the exact block lines a maintainer would review and paste for a new pin.
//! 2. **Extraction.** The narrow readers in [`ts`] (faker `.ts`) and [`cldr`] (CLDR XML) accept the
//!    exact shapes the pinned files use, and anything else is an error, never a guess. Faker's
//!    own locale fallback chain (`src/locale/<locale>.ts`, for example `de_AT` → `de` → `en`)
//!    picks the file for each key. The per-country choices are data in [`COUNTRIES`].
//! 3. **Content rules and caps** (ADR 0079 §5): entries that break a rule are dropped and
//!    counted, never repaired; lists over their cap keep a fixed-seed sample ([`SplitMix64`],
//!    [`SEED`]); lists built from faker's patterns are expanded with the same generator.
//! 4. **Output.** [`render`] writes the file in the format the `rizzy-client` parser reads,
//!    [`validate()`] re-checks it, and the generated section of [`SOURCES`] (sizes, SHA-256, drop
//!    counts, decisions) is rewritten. `--check` regenerates both and fails on any byte
//!    difference instead of writing. CI cannot run it, because the checkouts are not committed.

